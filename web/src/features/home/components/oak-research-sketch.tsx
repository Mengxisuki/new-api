const leaves = leafClusters.flatMap(([cx, cy, rx, ry], cluster) =>
  // 单次展开生成所有叶片的坐标与变换参数
  Array.from({ length: 20 }, (_, index) => {
    // 每簇数量固定，避免动画或随机采样的布局抖动
    const angle = index * 2.39996 + cluster // 簇索引错开角度，让各簇不会出现完全重复排列
    const radius = Math.sqrt((index + 0.5) / 20) // 半步偏移避免中心点重合，平方根改善面内分布
    return [
      cx + Math.cos(angle) * radius * rx, // 横向位置按所在簇的半径缩放
      cy + Math.sin(angle) * radius * ry, // 纵向位置与横向共享采样半径
      Math.sin(angle + cluster) * 75, // 叶片旋转限定在固定范围内，保持历史构图
      0.42 + (index % 4) * 0.06, // 四档缩放增加层次，且不会随时间改变
    ]
  })
)

